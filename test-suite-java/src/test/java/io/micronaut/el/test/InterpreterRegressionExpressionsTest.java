package io.micronaut.el.test;

import io.micronaut.el.CompiledELContext;
import io.micronaut.el.CompiledExpressionFactory;
import jakarta.el.ELContext;
import jakarta.el.ELException;
import jakarta.el.ExpressionFactory;
import jakarta.el.ValueExpression;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;

/**
 * The compile-time counterparts of {@code InterpreterRegressionTest}: the same expression texts, generated by the
 * processor, with the same expected results.
 */
class InterpreterRegressionExpressionsTest {

    private static final int ELEMENTS = InterpreterRegressionBean.ELEMENTS;

    private final ELContext context = new CompiledELContext().setBean("bean", new InterpreterRegressionBean());
    private final ExpressionFactory factory = new CompiledExpressionFactory(
        List.of(new InterpreterRegressionExpressions$ELExpressions()));

    @Test
    void longOrdinaryExpressionsCompile() {
        assertEquals("x".repeat(17_000) + "${1}", InterpreterRegressionExpressions.LONG_TEXT);
        assertEquals("x".repeat(17_000) + "1", value(InterpreterRegressionExpressions$ELExpressions.LONG_TEXT));
        assertEquals(600, ((List<?>) value(InterpreterRegressionExpressions$ELExpressions.LONG_LIST)).size());
        assertEquals("1 ".repeat(300), value(InterpreterRegressionExpressions$ELExpressions.MANY_PARTS));
        assertEquals(150L, value(InterpreterRegressionExpressions$ELExpressions.LONG_SUM));
        assertEquals(true, value(InterpreterRegressionExpressions$ELExpressions.LONG_CONJUNCTION));
        assertEquals("a".repeat(120), value(InterpreterRegressionExpressions$ELExpressions.LONG_CONCATENATION));
        assertEquals("a", value(InterpreterRegressionExpressions$ELExpressions.LONG_TRIM_CHAIN));
        // the factory finds each one by the text the interpreted test builds
        for (String text : List.of("x".repeat(17_000) + "${1}", "${[" + "1,".repeat(599) + "1]}", "${1} ".repeat(300),
            "${" + "1+".repeat(149) + "1}", "${" + "true and ".repeat(109) + "true}",
            "${" + "'a' += ".repeat(119) + "'a'}", "${' a '" + ".trim()".repeat(120) + "}")) {
            assertInstanceOf(io.micronaut.el.runtime.CompiledExpression.class,
                factory.createValueExpression(context, text, Object.class), text.substring(0, 20));
        }
    }

    @Test
    void aDefaultMethodOfAPlatformInterfaceIsInvoked() {
        assertEquals("11", value(InterpreterRegressionExpressions$ELExpressions.PLATFORM_DEFAULT_METHOD));
        assertEquals("21", value(InterpreterRegressionExpressions$ELExpressions.APPLICATION_DEFAULT_METHOD));
    }

    @Test
    void aLambdaPresentedAsAnInterfaceIsInvokedConcurrently() {
        List<?> mapped = (List<?>) value(InterpreterRegressionExpressions$ELExpressions.PARALLEL_MAP);
        assertEquals(ELEMENTS, mapped.size());
        for (int i = 0; i < ELEMENTS; i++) {
            assertEquals((long) i, mapped.get(i));
        }
        List<?> nested = (List<?>) value(InterpreterRegressionExpressions$ELExpressions.NESTED_PARALLEL_MAP);
        assertEquals(ELEMENTS, nested.size());
        assertEquals(5L, nested.get(0));
        assertEquals((long) ELEMENTS + 4, nested.get(ELEMENTS - 1));
    }

    @Test
    void aMethodNamedNullIsRejected() {
        assertThrows(ELException.class, () -> value(InterpreterRegressionExpressions$ELExpressions.NULL_METHOD_NAME));
        assertThrows(ELException.class,
            () -> value(InterpreterRegressionExpressions$ELExpressions.NULL_METHOD_NAME_WITH_ARGUMENT));
        assertNull(value(InterpreterRegressionExpressions$ELExpressions.NULL_PROPERTY_NAME));
    }

    @Test
    void theResultOfAMethodExpressionIsNotCoercedToTheExpectedReturnType() {
        assertEquals("n", InterpreterRegressionExpressions$ELExpressions.UNCOERCED_NAME.invoke(context, new Object[0]));
        assertEquals(2, InterpreterRegressionExpressions$ELExpressions.UNCOERCED_TWO.invoke(context, new Object[0]));
        assertEquals("n", InterpreterRegressionExpressions$ELExpressions.UNCOERCED_PROVIDED_NAME.invoke(context, null));
        // a literal-expression is still coerced, by the section 1.2.1.2
        assertEquals(5, factory.createMethodExpression(context, "5", Integer.class, new Class<?>[0])
            .invoke(context, new Object[0]));
    }

    private Object value(ValueExpression expression) {
        return expression.getValue(context);
    }
}
